------------------------------------------------------------GROUP BY AND HAVING--------------------------------------------------------------------------------------------
/*
	GROUP BY ------> It helps in clubbing multiple records for each and every category

	HAVING   ------> It helps in performing the filtering of aggrgated records for every category

	Syntax:

	SELECT col_name, AGG(col)
	FROM   table_name
	GROUP BY col_name
	HAVING AGG(col) condition
*/
----------------------------------------------------------Solved Examples--------------------------------------------------------------------------------------------------
---1.	Display the number of employees in each department
SELECT department,COUNT(emp_name) AS Total_employees
FROM Employees 
WHERE department IS NOT NULL
GROUP BY department
ORDER BY 2 DESC
---2.	Display departments having more than 2 employees
SELECT department,COUNT(emp_name) AS Total_employees
FROM Employees 
WHERE department IS NOT NULL
GROUP BY department
HAVING COUNT(emp_name)>2
ORDER BY 2 DESC
---3.	Find the average salary of employees in each department
SELECT department,AVG(salary) AS Average_salary
FROM Employees 
WHERE department IS NOT NULL
GROUP BY department
ORDER BY 2 DESC
---4.	Display customer IDs having more than 3 orders
SELECT customer_id,COUNT(order_id) AS Total_orders
FROM orders 
WHERE customer_id IS NOT NULL
GROUP BY customer_id
HAVING COUNT(order_id) > 3
ORDER BY 2 DESC
---5.	Display payment modes having at least 2 successful payments
SELECT payment_mode,COUNT(payment_status) AS Total_Success_payment_status
FROM Payments1 
WHERE payment_status = 'Success'
GROUP BY payment_mode
HAVING COUNT(payment_status)>=2
ORDER BY 2 DESC

